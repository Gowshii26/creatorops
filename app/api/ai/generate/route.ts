import { NextResponse } from "next/server";
import { GoogleGenAI } from "@google/genai";

import { getWorkspaceContext } from "@/lib/auth/workspace";

type GenerateRequestBody = {
  brief?: string;
  campaignName?: string;
  platform?: string;
  existingHashtags?: string;
  brandVoice?: string;
};

type GeminiResult = {
  caption: string;
  hashtags: string[];
  visualConcept: string;
};

const allowedRoles = new Set([
  "admin",
  "manager",
  "creator",
]);

const responseSchema = {
  type: "object",
  properties: {
    caption: {
      type: "string",
      description:
        "A polished social media caption based on the supplied marketing brief.",
    },
    hashtags: {
      type: "array",
      items: {
        type: "string",
      },
      description:
        "A list of relevant social media hashtags. Each hashtag should start with #.",
    },
    visualConcept: {
      type: "string",
      description:
        "A concise visual creative concept describing what the social media image or video could look like.",
    },
  },
  required: [
    "caption",
    "hashtags",
    "visualConcept",
  ],
  additionalProperties: false,
};

export async function POST(request: Request) {
  try {
    /*
     * --------------------------------------------------
     * 1. Authenticate user and load workspace context
     * --------------------------------------------------
     */

    const workspaceResult =
      await getWorkspaceContext();

    if (!workspaceResult.data) {
      return NextResponse.json(
        {
          error:
            workspaceResult.error ||
            "Workspace access denied.",
        },
        {
          status:
            workspaceResult.status || 401,
        }
      );
    }

    const workspace = workspaceResult.data;

    /*
     * --------------------------------------------------
     * 2. Restrict AI generation by role
     * --------------------------------------------------
     */

    if (!allowedRoles.has(workspace.role)) {
      return NextResponse.json(
        {
          error:
            "AI content generation is available only to Administrators, Managers and Creators.",
        },
        {
          status: 403,
        }
      );
    }

    /*
     * --------------------------------------------------
     * 3. Ensure Gemini API key exists
     * --------------------------------------------------
     */

    const apiKey =
      process.env.GEMINI_API_KEY;

    if (!apiKey) {
      console.error(
        "GEMINI_API_KEY is missing."
      );

      return NextResponse.json(
        {
          error:
            "AI service is not configured.",
        },
        {
          status: 500,
        }
      );
    }

    /*
     * --------------------------------------------------
     * 4. Read and validate request
     * --------------------------------------------------
     */

    const body =
      (await request.json()) as GenerateRequestBody;

    const brief =
      body.brief?.trim() || "";

    const campaignName =
      body.campaignName?.trim() || "";

    const platform =
      body.platform?.trim() ||
      "Social Media";

    const existingHashtags =
      body.existingHashtags?.trim() || "";

    const brandVoice =
      body.brandVoice?.trim() || "";

    if (brief.length < 5) {
      return NextResponse.json(
        {
          error:
            "Please provide a content brief of at least 5 characters.",
        },
        {
          status: 400,
        }
      );
    }

    /*
     * --------------------------------------------------
     * 5. Build prompt
     * --------------------------------------------------
     */

    const prompt = `
You are an AI content assistant inside CreatorOps,
a marketing content planning and approval platform.

Your job is to create a DRAFT for a human creator.

The AI must never claim that the content is approved,
published, medically validated, legally approved,
or guaranteed to perform.

CAMPAIGN:
${campaignName || "Not specified"}

PLATFORM:
${platform}

CONTENT BRIEF:
${brief}

EXISTING HASHTAGS:
${existingHashtags || "None supplied"}

BRAND VOICE:
${brandVoice || "Professional, clear, engaging and natural"}

Generate:

1. One polished social-media caption.
2. Between 5 and 10 relevant hashtags.
3. One concise visual concept for the creative team.

Requirements:

- Keep the caption appropriate for the specified platform.
- Avoid unsupported factual claims.
- Do not invent product certifications, statistics,
  medical claims, prices or guarantees.
- Use natural marketing language.
- Do not mention that the content was generated by AI.
- Hashtags must start with #.
- The visual concept should describe composition,
  subject, mood and overall creative direction.
- The result is a draft and will go through
  human review inside CreatorOps.
`;

    /*
     * --------------------------------------------------
     * 6. Call Gemini
     * --------------------------------------------------
     */

    const ai = new GoogleGenAI({
      apiKey,
    });

    const interaction =
      await ai.interactions.create({
        model: "gemini-3.8-flash",

        input: prompt,

        response_format: {
          type: "text",
          mime_type:
            "application/json",
          schema: responseSchema,
        },
      });

    const output =
      interaction.output_text;

    if (!output) {
      throw new Error(
        "Gemini returned an empty response."
      );
    }

    /*
     * --------------------------------------------------
     * 7. Parse structured response
     * --------------------------------------------------
     */

    const parsed =
      JSON.parse(output) as GeminiResult;

    if (
      !parsed.caption ||
      !Array.isArray(parsed.hashtags) ||
      !parsed.visualConcept
    ) {
      throw new Error(
        "Gemini returned an invalid response."
      );
    }

    /*
     * --------------------------------------------------
     * 8. Clean hashtags
     * --------------------------------------------------
     */

    const hashtags =
      parsed.hashtags
        .map((hashtag) => {
          const cleaned =
            hashtag.trim();

          if (!cleaned) {
            return "";
          }

          return cleaned.startsWith("#")
            ? cleaned
            : `#${cleaned}`;
        })
        .filter(Boolean)
        .slice(0, 10);

    /*
     * --------------------------------------------------
     * 9. Return result
     * --------------------------------------------------
     */

    return NextResponse.json({
      generation: {
        caption:
          parsed.caption.trim(),

        hashtags,

        visualConcept:
          parsed.visualConcept.trim(),
      },

      metadata: {
        aiGenerated: true,
        model:
          "gemini-3.8-flash",
      },
    });
  } catch (error) {
    console.error(
      "AI generation error:",
      error
    );

    return NextResponse.json(
      {
        error:
          "Unable to generate AI content right now.",
      },
      {
        status: 500,
      }
    );
  }
}